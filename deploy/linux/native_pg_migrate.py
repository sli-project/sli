"""Upgrade an installed native schema over local peer auth, without secrets.

Fresh bootstrap and application/worker account provisioning remain separate.
The package coordinator fences writers and verifies its checkpoint first.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import subprocess
import sys

from deploy.linux import native_pg_inventory as inventory
from deploy.linux.existing_postgres_bootstrap import base_schema_markers, forward_migration_inventory
from deploy.linux.native_pg_inventory import migration_checksum_variants
from deploy.linux.operation_wait import made_progress


ERRORS = (
    "native_pg_migration_ledger_mismatch", "native_pg_migration_checksum_mismatch",
    "native_pg_migration_readback_failed", "native_pg_migration_owner_required",
)


def psql_error_tail(error: str) -> str:
    """Keep PostgreSQL diagnostics, never echoed SQL, rows or connection data."""
    lines = []
    for line in error.splitlines()[-20:]:
        # DETAIL/CONTEXT/LINE can contain customer rows or the SQL statement.
        match = re.search(r"(?:^|:\d+:\s+)((?:ERROR|FATAL|PANIC):\s+.+)", line)
        if not match:
            continue
        message = match.group(1)
        if re.search(r"(?i)\b(?:postgres(?:ql)?://|(?:pg)?password\b|passfile\b|(?:host|hostaddr|dbname|user|port|service|sslkey)\s*=)", message):
            message = "PostgreSQL: [connection diagnostic redacted]"
        # PostgreSQL primary messages may quote a rejected input value.
        message = re.sub(r"'[^']*'|\"[^\"]*\"", "[redacted]", message)
        # Prevent terminal control sequences in server-provided text.
        lines.append("".join(c for c in message if c.isprintable())[:1000])
    return "\n".join(lines)


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def transactional_sql(body: str) -> str:
    """Render pinned migration SQL for the coordinator's fenced, offline batch.

    Only top-level transaction boundaries and index concurrency change. Quoted
    function bodies, identifiers, data and comments must remain byte-for-byte.
    Online indexes use ordinary transactional DDL while writers are fenced;
    this also covers the index commands generated by migration 357's gexec.
    Other commands requiring autocommit fail inside the batch and roll it back.
    """
    token = re.compile(r"\s+|--[^\n]*|[eE]'(?:\\.|''|[^'\\])*'|'(?:''|[^'])*'"
                       r'|"(?:""|[^"])*"|(?P<tag>\$(?:[A-Za-z_][A-Za-z_0-9]*)?\$).*?(?P=tag)'
                       r"|[A-Za-z_][A-Za-z_0-9$]*|\\[^\s;]+|.", re.DOTALL)
    changes = []
    statement = []
    offset = 0
    while offset < len(body):
        # PostgreSQL block comments nest; do not interpret their contents.
        if body.startswith("/*", offset):
            depth = 1
            offset += 2
            while depth:
                if offset >= len(body):
                    raise ValueError("native_pg_migration_sql_unsupported")
                if body.startswith("/*", offset):
                    depth += 1
                    offset += 2
                elif body.startswith("*/", offset):
                    depth -= 1
                    offset += 2
                else:
                    offset += 1
            continue
        match = token.match(body, offset)
        word = match.group()
        start, offset = match.span()
        if word.isspace() or word.startswith("--"):
            continue
        if word.startswith("\\") and word != r"\gexec":
            raise ValueError("native_pg_migration_sql_unsupported")
        statement.append((word, start, offset))
        if word not in (";", r"\gexec"):
            continue
        words = [part[0].lower() for part in statement]
        if words[0] in {"begin", "start", "commit", "end", "rollback", "abort", "prepare"}:
            if words not in (["begin", ";"], ["begin", "work", ";"], ["begin", "transaction", ";"],
                             ["start", "transaction", ";"], ["commit", ";"], ["commit", "work", ";"],
                             ["commit", "transaction", ";"], ["end", ";"]):
                raise ValueError("native_pg_migration_sql_unsupported")
            changes.append((statement[0][1], offset, ""))
        elif words[0] in {"create", "drop"}:
            index = 2 if words[:2] == ["create", "unique"] else 1
            if words[index:index + 2] == ["index", "concurrently"]:
                _, begin, end = statement[index + 1]
                changes.append((begin, end, ""))
        elif word == r"\gexec":
            # Restrict generated SQL to the existing SELECT format(index DDL)
            # path. Never rewrite arbitrary data strings or function bodies.
            if words[:3] != ["select", "format", "("]:
                raise ValueError("native_pg_migration_sql_unsupported")
            value, begin, end = statement[3]
            offline, count = re.subn(r"(?i)^('(create(?:\s+unique)?|drop)\s+index)\s+concurrently\b",
                                     r"\1", value)
            if count != 1:
                raise ValueError("native_pg_migration_sql_unsupported")
            changes.append((begin, end, offline))
        statement = []
    if statement:
        raise ValueError("native_pg_migration_sql_unsupported")
    for start, end, replacement in reversed(changes):
        body = body[:start] + replacement + body[end:]
    return body


def upgrade_sql(root: Path) -> str:
    """Verify all release SQL before constructing the peer session's script.

    NULL hashes admit only the same version/name with pinned package content.
    An existing non-NULL attestation is never overwritten. Both historical
    checkout line endings are accepted, as in native_pg_inventory.
    """
    manifest = json.loads((root / "deploy/linux/native_pg_ledger.json").read_text())
    inventory.verify_manifest(root, manifest)
    expected = inventory.expected_ledger(root)
    migrations = forward_migration_inventory(root / "config/postgres_migrations")
    schema = root / "config/postgres_schema_v8.sql"
    sources = {version: schema for version, _ in base_schema_markers(schema)}
    sources.update((item.version, item.path) for item in migrations)
    rows = []
    for row in expected:
        variants = sorted(migration_checksum_variants(sources[row["version"]].read_bytes()))
        rows.append(f"({row['version']},{literal(row['name'])},{literal(row['sha256'])},"
                    "array[" + ",".join(map(literal, variants)) + "])")
    # One peer session holds the bootstrap lock. The package coordinator has
    # fenced writers before entering this single transaction, including indexes.
    parts = [r"""\set ON_ERROR_STOP on
set statement_timeout=0;
set lock_timeout=0;
set standard_conforming_strings=on;
select pg_advisory_lock(hashtext('sli_linux_stand_migrate'));
begin;
do $$ begin
    if session_user <> 'postgres'
       or not pg_has_role(session_user,'adlog_storage_owner','MEMBER') then
        raise exception 'native_pg_migration_owner_required';
    end if;
end $$;
create temp table sli_upgrade_expected(version int primary key,name text,sha256 text,variants text[]);
insert into sli_upgrade_expected values
""", ",\n".join(rows), ";\n", """
do $$ begin
    if not exists(select 1 from public.schema_migrations)
       or exists(select 1 from public.schema_migrations m
                 left join sli_upgrade_expected e using(version)
                 where e.version is null or m.name is distinct from e.name)
       or exists(select 1 from sli_upgrade_expected e
                 where e.version < (select max(version) from public.schema_migrations)
                   and not exists(select 1 from public.schema_migrations m where m.version=e.version)) then
        raise exception 'native_pg_migration_ledger_mismatch';
    end if;
    if exists(select 1 from public.schema_migrations m join sli_upgrade_expected e using(version)
              where to_jsonb(m)->>'sha256' is not null
                and not ((to_jsonb(m)->>'sha256')=any(e.variants))) then
        raise exception 'native_pg_migration_checksum_mismatch';
    end if;
end $$;
alter table public.schema_migrations add column if not exists sha256 text;
"""]
    for item in migrations:
        enter, leave = "set role adlog_storage_owner;", "reset role;"
        if (item.version, item.name) == (397, "problem_queue_workflow"):
            # The published preflight reads the report catalog before SET ROLE.
            # The existing NOLOGIN migrator has runtime catalog access and can
            # switch to the storage owner for DDL. RESET ROLE in the migration
            # returns to that migrator for the ledger insert.
            enter = "set local session authorization adlog_storage_migrator;"
            leave = "reset session authorization;"
        elif (item.version, item.name) == (406, "native_radius_accounting_admission"):
            # The published migration uses the peer session for the temporary
            # schema grant and revoke, and switches to the owning roles for DDL.
            if manifest["files"][item.path.relative_to(root).as_posix()] != (
                    "ad1f1d4c269bc3834ca7cc934e2195982ee0ac18df3b8525557109db6392826a"):
                raise ValueError("native_pg_sql_inventory_mismatch")
            enter = "reset role;"
        parts.extend([
            f"select not exists(select 1 from public.schema_migrations where version={item.version})"
            " as sli_upgrade_pending \\gset\n\\if :sli_upgrade_pending\n",
            f"\\echo PostgreSQL: migration {item.version}\n{enter}\n",
            transactional_sql(item.path.read_text(encoding="utf-8")), f"\n{leave}\n",
            f"""do $$ begin
    if not exists(select 1 from public.schema_migrations
                  where version={item.version} and name={literal(item.name)}) then
        raise exception 'native_pg_migration_readback_failed';
    end if;
end $$;
\\endif
"""])
    parts.append("""
do $$ begin
    if exists(select 1 from sli_upgrade_expected e full join public.schema_migrations m using(version)
              where e.version is null or m.version is null or m.name is distinct from e.name) then
        raise exception 'native_pg_migration_readback_failed';
    end if;
    if exists(select 1 from public.schema_migrations m join sli_upgrade_expected e using(version)
              where m.sha256 is not null and not (m.sha256=any(e.variants))) then
        raise exception 'native_pg_migration_checksum_mismatch';
    end if;
end $$;
update public.schema_migrations m set sha256=e.sha256
    from sli_upgrade_expected e where m.version=e.version and m.sha256 is null;
commit;
select pg_advisory_unlock(hashtext('sli_linux_stand_migrate'));
""")
    return "".join(parts)


def run_sql(body: str) -> None:
    """Installer's local peer path; no passfile, inherited PG settings or timeout."""
    argv = ["runuser", "-u", "postgres", "--", "/usr/lib/postgresql/18/bin/psql",
            "-XqAt", "-w", "-h", "/var/run/postgresql", "-p", "5432", "-U", "postgres",
            "-d", "sli", "-v", "ON_ERROR_STOP=1"]
    process = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                               text=True, encoding="utf-8",
                               env={"PATH": "/usr/sbin:/usr/bin:/sbin:/bin", "LC_ALL": "C.UTF-8",
                                    "PGAPPNAME": "sli-package-migrate", "PGCLIENTENCODING": "UTF8"})
    try:
        made_progress()
        while True:
            try:
                _, error = process.communicate(body, timeout=10)
                break
            except subprocess.TimeoutExpired as waiting:
                body = None
                output = waiting.output or b""
                if isinstance(output, bytes):
                    output = output.decode("utf-8", errors="replace")
                cursor = re.findall(r"(?m)^PostgreSQL: migration ([0-9]+)\r?$", output)
                step = "миграция " + cursor[-1] if cursor else "проверка ledger"
                print(f"PostgreSQL: {step}; процесс {process.pid} жив, выполняет SQL или ожидает блокировку.", flush=True)
                # Keep the existing coordinator's silence watchdog informed.
                # A live peer client may legitimately wait for a PostgreSQL lock.
                made_progress()
        if process.returncode:
            diagnostic = psql_error_tail(error)
            if diagnostic:
                # Emit before recovery, including when the coordinator exposes
                # only an allowlisted reason code at its command boundary.
                print(diagnostic, file=sys.stderr, flush=True)
            code = next((code for code in ERRORS if re.search(r"ERROR:\s+" + code + r"(?:\s|$)", error)),
                        "native_pg_migration_failed")
            failure = RuntimeError(code)
            if diagnostic:
                failure.add_note(diagnostic)
            raise failure
        made_progress()
    finally:
        if process.poll() is None:
            process.terminate()
            process.communicate()


def migrate(root: Path) -> None:
    run_sql(upgrade_sql(root))
    print("native_pg_migrations_verified", flush=True)
