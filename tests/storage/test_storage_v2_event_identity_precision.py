"""Native 100 ns timestamps must reserve the identity used by core publication."""
import os
from uuid import uuid4

import pytest

from server.sli.storage.storage_v2_models import parse_utc_timestamp
from server.sli.storage.storage_v2_repository import PostgresStorageV2Repository
from tests.postgres_integration_guard import assert_disposable_database


@pytest.fixture
def repository():
    psycopg = pytest.importorskip("psycopg")
    from psycopg import sql
    from psycopg.conninfo import conninfo_to_dict
    from psycopg.rows import dict_row

    dsn = os.environ.get("ADLOG_TEST_PG_DSN")
    if not dsn:
        pytest.skip("disposable PostgreSQL required")
    database = "sli_test_identity_precision_" + uuid4().hex
    with psycopg.connect(dsn, autocommit=True) as admin:
        assert_disposable_database(admin)
        admin.execute(sql.SQL("create database {}").format(sql.Identifier(database)))
        try:
            parts = conninfo_to_dict(dsn)
            parts["dbname"] = database
            connect = lambda: psycopg.connect(**parts, row_factory=dict_row)
            with connect() as conn:
                conn.execute("""create table storage_v2_event_identity_allocations(
                    id bigint generated by default as identity primary key,
                    server_id bigint,channel_id int,event_record_id bigint,
                    time_created_utc timestamptz,normalized_hash bytea,
                    unique(server_id,channel_id,event_record_id,time_created_utc));
                    create table events_v2_core(id bigint primary key,normalized_hash bytea,
                        server_id bigint,channel_id int,event_record_id bigint,time_created_utc timestamptz);""")
            yield PostgresStorageV2Repository(connect), connect
        finally:
            admin.execute(sql.SQL("drop database {} with (force)").format(sql.Identifier(database)))


@pytest.mark.postgres_integration
@pytest.mark.postgres_empty
@pytest.mark.parametrize("fraction", ["000125500", "000126500", "000248500", "999999500"])
def test_native_precision_reservation_matches_core_and_replays(repository, fraction):
    repo, connect = repository
    event = {"server_id": 1, "channel_id": 1, "event_record_id": 1,
             "time_created_utc": f"2026-10-11T00:00:00.{fraction}Z",
             "normalized_hash": "ab" * 32}
    reserved = repo.reserve_event_identities([event])[0]
    with connect() as conn:
        stored = conn.execute("select time_created_utc from storage_v2_event_identity_allocations").fetchone()
        assert stored["time_created_utc"] == parse_utc_timestamp(event["time_created_utc"])
        conn.execute("insert into events_v2_core values(%s,%s,1,1,1,%s)",
                     (reserved["id"], bytes.fromhex(event["normalized_hash"]), stored["time_created_utc"]))
    replay = repo.reserve_event_identities([event])[0]
    assert replay["id"] == reserved["id"] and replay["published"]
    with pytest.raises(RuntimeError, match="allocation hash mismatch"):
        repo.reserve_event_identities([{**event, "normalized_hash": "cd" * 32}])
    with connect() as conn:
        conn.execute("update storage_v2_event_identity_allocations set normalized_hash=%s", (bytes.fromhex("cd" * 32),))
    with pytest.raises(RuntimeError, match="allocation hash mismatch"):
        repo.reserve_event_identities([event])


@pytest.mark.postgres_integration
@pytest.mark.postgres_empty
def test_existing_core_identity_wins_over_legacy_precision_reservation(repository):
    repo, connect = repository
    at = "2026-10-11T00:00:00.000125500Z"
    event = {"server_id": 1, "channel_id": 1, "event_record_id": 1,
             "time_created_utc": at, "normalized_hash": "ab" * 32}
    with connect() as conn:
        conn.execute("insert into storage_v2_event_identity_allocations values(100,1,1,1,%s,%s)",
                     (at, bytes.fromhex(event["normalized_hash"])))
        conn.execute("insert into events_v2_core values(100,%s,1,1,1,%s)",
                     (bytes.fromhex(event["normalized_hash"]), parse_utc_timestamp(at)))
    result = repo.reserve_event_identities([event])[0]
    assert result["id"] == 100 and result["published"]
