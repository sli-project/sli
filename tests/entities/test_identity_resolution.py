def test_причины_только_из_закрытого_списка() -> None:
    """Причина должна поддаваться подсчёту, иначе доля unresolved не измеряется."""
    случаи = [
        {"sam": "-"}, {"sam": "ivanov"}, {}, {"sid": "S-1-5-18"},
        {"sid": "S-1-0-0"},
    ]
    for кв in случаи:
        о = разрешить_субъект(**кв)
        if о.причина is not None:
            assert о.причина in ПРИЧИНЫ, (кв, о.причина)


def test_из_события_по_умолчанию_смотрит_target() -> None:
    """В 4624 вошедшая учётная запись лежит в target_*, а не в subject_*.

    Эта ошибка допускалась при разборе корпуса дважды, поэтому умолчание
    выбрано так, чтобы неверный вариант приходилось указывать явно.
    """
    событие = {
        "subject_user_sid": "S-1-5-18", "subject_user_name": "DC1$",
        "target_user_sid": ДОМЕННЫЙ, "target_user_name": "ivanov",
        "target_domain_name": "EXAMPLE", "computer_name": "DC1",
    }
    assert разрешить_из_события(событие).ключ == f"sid:{ДОМЕННЫЙ}"
    assert разрешить_из_события(событие, роль="subject").ключ == "sid:dc1:S-1-5-18"


