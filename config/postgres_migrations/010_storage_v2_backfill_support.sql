create table if not exists storage_v2_backfill_chunks (
    worker_name text not null references storage_v2_backfill_checkpoints(worker_name) on delete cascade,
    chunk_start_event_id bigint not null,
    chunk_end_event_id bigint not null,
    source_event_rows integer not null check (source_event_rows >= 0),
    target_event_rows integer not null check (target_event_rows >= 0),
    source_link_rows bigint not null default 0 check (source_link_rows >= 0),
    target_link_rows bigint not null default 0 check (target_link_rows >= 0),
    source_sha256 bytea not null check (octet_length(source_sha256) = 32),
    target_sha256 bytea not null check (octet_length(target_sha256) = 32),
    archive_event_set_id uuid references storage_v2_archive_sets(archive_set_id),
    archive_link_set_id uuid references storage_v2_archive_sets(archive_set_id),
    wal_bytes bigint,
    duration_ms bigint not null check (duration_ms >= 0),
    status text not null check (status in ('verified', 'failed', 'rolled_back')),
    completed_at timestamptz not null default now(),
    primary key (worker_name, chunk_start_event_id, chunk_end_event_id),
    constraint storage_v2_backfill_chunks_range check (chunk_start_event_id <= chunk_end_event_id)
);

create table if not exists storage_v2_outbox (
    id bigint generated by default as identity primary key,
    batch_id uuid not null unique,
    first_event_id bigint not null,
    last_event_id bigint not null,
    event_count integer not null check (event_count > 0),
    event_ids bigint[] not null,
    identity_sha256 bytea not null check (octet_length(identity_sha256) = 32),
    state text not null default 'pending' check (state in ('pending', 'leased', 'completed', 'failed', 'quarantined')),
    attempt_count integer not null default 0 check (attempt_count >= 0),
    available_at timestamptz not null default now(),
    lease_token uuid,
    lease_until timestamptz,
    last_error text,
    created_at timestamptz not null default now(),
    completed_at timestamptz,
    constraint storage_v2_outbox_range check (first_event_id <= last_event_id),
    constraint storage_v2_outbox_ids_count check (cardinality(event_ids) = event_count),
    constraint storage_v2_outbox_ids_bounds check (
        event_ids[1] = first_event_id and event_ids[event_count] = last_event_id
    )
);

create table if not exists storage_v2_shadow_results (
    id bigint generated by default as identity primary key,
    query_kind text not null,
    sample_key_sha256 bytea not null check (octet_length(sample_key_sha256) = 32),
    v1_result_sha256 bytea not null check (octet_length(v1_result_sha256) = 32),
    v2_result_sha256 bytea not null check (octet_length(v2_result_sha256) = 32),
    identity_match boolean not null,
    count_match boolean not null,
    v1_duration_ms double precision not null check (v1_duration_ms >= 0),
    v2_duration_ms double precision not null check (v2_duration_ms >= 0),
    mismatch_summary text,
    observed_at timestamptz not null default now()
);

create index if not exists idx_storage_v2_outbox_claim
    on storage_v2_outbox(state, available_at, lease_until, id);
create index if not exists idx_storage_v2_shadow_kind_time
    on storage_v2_shadow_results(query_kind, observed_at desc);
create index if not exists idx_storage_v2_shadow_mismatch
    on storage_v2_shadow_results(observed_at desc)
    where not identity_match or not count_match;

grant select, insert, update, delete on table
    storage_v2_provider, storage_v2_channel, storage_v2_computer, storage_v2_keywords,
    storage_v2_domain_name, storage_v2_role, storage_v2_extracted_from, storage_v2_entity_type,
    events_v2_core, event_facts_v2, entities_v2, entity_details_v2, event_entity_link_blocks_v2,
    storage_v2_archive_sets, storage_v2_archive_blocks, storage_v2_backfill_checkpoints,
    storage_v2_backfill_chunks, storage_v2_outbox, storage_v2_shadow_results
    to adlog_storage_worker;
grant select on event_entity_links_v2 to adlog_storage_worker;
grant usage, select on sequence
    storage_v2_provider_id_seq, storage_v2_channel_id_seq, storage_v2_computer_id_seq,
    storage_v2_keywords_id_seq, storage_v2_domain_name_id_seq, storage_v2_role_id_seq,
    storage_v2_extracted_from_id_seq, storage_v2_entity_type_id_seq,
    storage_v2_outbox_id_seq, storage_v2_shadow_results_id_seq
    to adlog_storage_worker;

