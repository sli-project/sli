-- Additive phase for compact event-catalog revision attribution.
-- The legacy text column remains authoritative until a separately accepted
-- read/write cutover and destructive removal.  Existing rows are backfilled
-- only through event_catalog_revision_reference_migrate.py.
begin;

select pg_advisory_xact_lock(
    hashtext('ad_log_reports_event_catalog_revision_reference_v51')
);

do $$
begin
    if not pg_has_role(session_user, 'adlog_storage_owner', 'MEMBER') then
        raise exception 'migration 051 requires membership in adlog_storage_owner';
    end if;
    if not exists (
        select 1 from schema_migrations
        where version=50 and name='semantic_worker_least_privilege'
    ) then
        raise exception 'migration 051 requires migration 050';
    end if;
    if not exists (
        select 1 from schema_migrations
        where version=49 and name='event_noise_browse_index'
    ) then
        raise exception 'migration 051 requires migration 049';
    end if;
    if to_regclass('events_v2_core') is null then
        raise exception 'migration 051 requires events_v2_core';
    end if;
    if exists (
        select 1 from events_v2_core
        where noise_catalog_version='pending-backfill'
        limit 1
    ) then
        raise exception 'migration 051 requires the migration 048 backfill to be complete';
    end if;
end
$$;

set local role adlog_storage_owner;

create table if not exists event_catalog_revisions(
    id smallint generated by default as identity primary key,
    version text not null unique,
    created_at timestamptz not null default now(),
    constraint event_catalog_revisions_version_nonempty
        check(length(version) between 1 and 255)
);

insert into event_catalog_revisions(version)
select distinct noise_catalog_version
from events_v2_core
on conflict(version) do nothing;

alter table events_v2_core
    add column if not exists noise_catalog_revision_id smallint;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname='events_v2_core_noise_catalog_revision_fk'
          and conrelid='events_v2_core'::regclass
    ) then
        alter table events_v2_core
            add constraint events_v2_core_noise_catalog_revision_fk
            foreign key(noise_catalog_revision_id)
            references event_catalog_revisions(id)
            not valid;
    end if;
end
$$;

create or replace function set_event_noise_catalog_revision()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog,public
as $$
begin
    select revision.id
      into new.noise_catalog_revision_id
      from public.event_catalog_revisions revision
     where revision.version=new.noise_catalog_version;
    if new.noise_catalog_revision_id is null then
        raise exception 'unregistered event catalogue revision: %',
            new.noise_catalog_version;
    end if;
    return new;
end
$$;

drop trigger if exists events_v2_core_catalog_revision on events_v2_core;
create trigger events_v2_core_catalog_revision
before insert or update of noise_catalog_version
on events_v2_core
for each row execute function set_event_noise_catalog_revision();

insert into schema_migrations(version,name)
values(51,'event_catalog_revision_reference')
on conflict(version) do update set name=excluded.name,applied_at=now();

commit;
