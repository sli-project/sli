    internal static void Validate(JsonObject obj)
    {
        foreach (var (key,value) in obj)
        {
            if (!Allowed.Contains(key)) throw new InvalidDataException("agent_gpo_governance_invalid");
            if (key=="gpo_settings") continue;
            if (value?.GetValueKind()==System.Text.Json.JsonValueKind.String && GpoGovernanceSettings.Count(value.GetValue<string>())>4096) throw new InvalidDataException("agent_gpo_governance_invalid");
            if (value is JsonArray array && (array.Count>256 || array.Any(x=>x?.GetValueKind()!=System.Text.Json.JsonValueKind.String || GpoGovernanceSettings.Count(x.GetValue<string>())>4096))) throw new InvalidDataException("agent_gpo_governance_invalid");
        }
        foreach (var key in new[] { "password_last_set_status","laps_password_expiration_status","legacy_laps_password_expiration_status" })
            if (obj.ContainsKey(key)) OneOf(obj[key], "observed not_set not_returned schema_absent parse_error");
        if (obj.ContainsKey("resource_based_delegation_status")) OneOf(obj["resource_based_delegation_status"], "observed partial not_returned schema_absent parse_error not_collected");
        if (obj["resource_based_delegation_sids"] is not null && (obj["resource_based_delegation_sids"] is not JsonArray sids || sids.Any(x=>x?.GetValueKind()!=System.Text.Json.JsonValueKind.String || !ValidSid(x.GetValue<string>())))) throw new InvalidDataException("agent_gpo_governance_invalid");
        if (obj["inactivity_basis"] is not null && (!Sli.Agent.Protocol.JsonRead.TryString(obj["inactivity_basis"],out var basis) || !new[] { "not_applicable", "last_logon", "creation_time_without_logon", "insufficient_time_evidence" }.Contains(basis,StringComparer.Ordinal))) throw new InvalidDataException("agent_gpo_governance_invalid");
        foreach (var key in new[] {"password_expiry_status","exact_last_logon_status"})
            if (obj.ContainsKey(key)) OneOf(obj[key], "observed not_collected not_evaluated missing_in_source no_record partial failed access_denied parse_error not_applicable");
    }
    private static void OneOf(JsonNode? value,string allowed)
    {
        var text=GpoGovernanceSettings.Text(value);
        if (!allowed.Split(' ').Contains(text,StringComparer.Ordinal)) throw new InvalidDataException("agent_gpo_governance_invalid");
    }
    private static bool ValidSid(string value)
    {
        if(!value.StartsWith("S-1-",StringComparison.Ordinal)) return false;
        var parts=value[4..].Split('-');
        return parts.Length>=2 && parts.All(p=>p.Length>0 && p.EnumerateRunes().All(r=>System.Text.Rune.GetUnicodeCategory(r)==System.Globalization.UnicodeCategory.DecimalDigitNumber));
    }
