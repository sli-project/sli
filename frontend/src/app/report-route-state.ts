import type { СостояниеПрав } from "./App";

/*
  Что показать на месте отчёта, пока самого отчёта нет.

  Дефект, из-за которого это вынесено в отдельную функцию: страница различала
  только «идёт загрузка» и «пришла ошибка данных», а состояние прав приходило
  одним значением `undefined` и для ожидания, и для отказа. При отказе сервера
  прав экран показывал «Загружаем разрешённые данные…» **бесконечно**.

  Найдено 02.08.2026 на живой копии: отчётные запросы падали по таймауту базы,
  и страница GPO висела на строке загрузки, хотя ответ был получен и был
  ошибкой. Ждать вечно хуже, чем увидеть отказ: пользователь считает, что
  система работает.

  Порядок проверок здесь — сам предмет решения, поэтому он вынесен из разметки
  и закреплён тестом.
*/

export type ЭкранОтчёта =
  | { вид: "отказ в правах" }
  | { вид: "загрузка" }
  | { вид: "ошибка данных"; сообщение: string }
  | { вид: "пусто"; заголовок: string }
  | { вид: "показывать отчёт" };

export function экранОтчёта(вход: {
  права: СостояниеПрав;
  загрузка: boolean;
  ошибка?: { message?: string } | null;
  пусто?: string;
}): ЭкранОтчёта {
  /*
    Отказ в правах проверяется первым и не смешивается с загрузкой: без прав
    запрос данных не делается вовсе, поэтому «загружается» было бы неправдой.
  */
  if (вход.права === "отказ") return { вид: "отказ в правах" };
  if (вход.загрузка) return { вид: "загрузка" };
  /*
    Ошибка важнее пустоты. Пустой результат — утверждение сервера о данных;
    ошибка означает, что утверждения не было вовсе (`B4`).
  */
  if (вход.ошибка) return { вид: "ошибка данных", сообщение: вход.ошибка.message || "причина не передана" };
  if (вход.пусто) return { вид: "пусто", заголовок: вход.пусто };
  return { вид: "показывать отчёт" };
}
