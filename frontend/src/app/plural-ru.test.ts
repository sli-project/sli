import { describe, expect, it } from "vitest";
import { ФОРМЫ, формаСлова, числоСоСловом } from "./plural-ru";

/*
  `О2`. Дефект был найден на живом экране («1 шагов»), а не тестом, потому что
  проверять было нечего: подпись собиралась склейкой в месте вывода. Здесь
  закрепляется правило, а не отдельная подпись.
*/

describe("склонение по числу", () => {
  it("берёт форму по последней цифре", () => {
    expect(формаСлова(1, ФОРМЫ.шаг)).toBe("шаг");
    expect(формаСлова(2, ФОРМЫ.шаг)).toBe("шага");
    expect(формаСлова(4, ФОРМЫ.шаг)).toBe("шага");
    expect(формаСлова(5, ФОРМЫ.шаг)).toBe("шагов");
    expect(формаСлова(0, ФОРМЫ.шаг)).toBe("шагов");
  });

  /*
    Главный случай, на котором ломаются наивные реализации: `11`–`14` берут
    форму «пять» независимо от последней цифры. Без него `21` и `11` дали бы
    одну форму.
  */
  it("одиннадцать–четырнадцать не следуют последней цифре", () => {
    for (const число of [11, 12, 13, 14, 111, 112, 113, 114]) {
      expect(формаСлова(число, ФОРМЫ.политика), String(число)).toBe("политик");
    }
    for (const число of [21, 101, 1001]) {
      expect(формаСлова(число, ФОРМЫ.политика), String(число)).toBe("политика");
    }
    for (const число of [22, 23, 24, 102]) {
      expect(формаСлова(число, ФОРМЫ.политика), String(число)).toBe("политики");
    }
  });

  it("не ломается на отрицательных и дробных", () => {
    expect(формаСлова(-1, ФОРМЫ.объект)).toBe("объект");
    expect(формаСлова(-5, ФОРМЫ.объект)).toBe("объектов");
    expect(формаСлова(2.7, ФОРМЫ.объект)).toBe("объекта");
  });

  /*
    Разделитель разрядов у русской локали — неразрывный пробел `U+00A0`, а не
    обычный. Это правильно: `1 400` не должно переноситься по строке. Но
    записывать его в ожидание видимым пробелом нельзя — тест выглядел бы
    совпавшим и падал. Поэтому здесь он назван кодом явно.

    Я на этом уже ошибся: первая версия теста ожидала обычный пробел, строки на
    экране были неразличимы, и расхождение нашлось только прогоном.
  */
  const НЕРАЗРЫВНЫЙ = " ";

  it("число выводится с неразрывным разделителем разрядов", () => {
    expect(числоСоСловом(1400, ФОРМЫ.учётнаяЗапись)).toBe(`1${НЕРАЗРЫВНЫЙ}400 учётных записей`);
    expect(числоСоСловом(1, ФОРМЫ.доказательство)).toBe("1 доказательство");
    expect(числоСоСловом(2, ФОРМЫ.доказательство)).toBe("2 доказательства");
    expect(числоСоСловом(999, ФОРМЫ.объект)).not.toContain(НЕРАЗРЫВНЫЙ);
  });

  /*
    Формы держатся в общем словаре именно чтобы одно существительное
    склонялось одинаково во всех отчётах. Тройка обязана быть тройкой разных
    слов: пара одинаковых форм означает, что кто-то заполнил её наспех.
  */
  it("каждая запись словаря содержит три различные формы", () => {
    for (const [имя, формы] of Object.entries(ФОРМЫ)) {
      expect(формы.length, имя).toBe(3);
      expect(new Set(формы).size, имя).toBe(3);
      for (const форма of формы) expect(форма.trim(), имя).not.toBe("");
    }
  });
});
