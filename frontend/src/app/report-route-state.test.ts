import { describe, expect, it } from "vitest";
import { экранОтчёта } from "./report-route-state";

/*
  Дефект, ради которого написан этот набор: при отказе сервера прав экран
  показывал строку загрузки бесконечно. Осмотром это неотличимо от медленного
  ответа — надо было дождаться и не дождаться.
*/

describe("что показывать вместо отчёта", () => {
  it("отказ в правах не выглядит загрузкой", () => {
    expect(экранОтчёта({ права: "отказ", загрузка: true })).toEqual({ вид: "отказ в правах" });
    expect(экранОтчёта({ права: "отказ", загрузка: false })).toEqual({ вид: "отказ в правах" });
  });

  /* Отказ важнее всего остального: без прав данные не запрашивались вовсе. */
  it("отказ в правах важнее ошибки данных и пустоты", () => {
    expect(экранОтчёта({ права: "отказ", загрузка: false, ошибка: new Error("500"), пусто: "нет строк" }).вид)
      .toBe("отказ в правах");
  });

  it("ожидание прав остаётся загрузкой", () => {
    expect(экранОтчёта({ права: "загружается", загрузка: true }).вид).toBe("загрузка");
  });

  /*
    `B4`. Пустой результат — утверждение сервера о данных; ошибка означает, что
    утверждения не было. Показать пустоту вместо ошибки значило бы выдать сбой
    за доказанное отсутствие.
  */
  it("ошибка данных важнее пустого состояния", () => {
    expect(экранОтчёта({ права: "получены", загрузка: false, ошибка: new Error("internal_server_error"), пусто: "Политики не найдены" }))
      .toEqual({ вид: "ошибка данных", сообщение: "internal_server_error" });
  });

  it("ошибка без текста не остаётся без объяснения", () => {
    expect(экранОтчёта({ права: "получены", загрузка: false, ошибка: {} }))
      .toEqual({ вид: "ошибка данных", сообщение: "причина не передана" });
  });

  it("пустое состояние показывается только когда данные действительно получены", () => {
    expect(экранОтчёта({ права: "получены", загрузка: false, пусто: "Политики не найдены" }))
      .toEqual({ вид: "пусто", заголовок: "Политики не найдены" });
  });

  it("при полученных данных без пустоты и ошибок рисуется сам отчёт", () => {
    expect(экранОтчёта({ права: "получены", загрузка: false }).вид).toBe("показывать отчёт");
  });
});
