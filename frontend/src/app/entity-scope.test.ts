import { describe, expect, it } from "vitest";
import { ТИПЫ_ОБСТОЯТЕЛЬСТВ, известныеТипыОбстоятельств, параметрыРежима, подписьРежима, числоВРежиме } from "./entity-scope";

const счётчики = [
  { entity_type: "auth_session", count: 2_682_365 },
  { entity_type: "ad_user", count: 4_120 },
  { entity_type: "ad_computer", count: 1_902 },
  { entity_type: "ip_address", count: 980 },
  { entity_type: "process", count: 165 },
];

describe("параметры режима", () => {
  it("обстоятельства запрашиваются перечнем, участники — его отрицанием", () => {
    const участники = параметрыРежима("участники", счётчики) ?? [];
    const обстоятельства = параметрыРежима("обстоятельства", счётчики) ?? [];
    expect(участники.every(([имя]) => имя === "exclude_entity_type")).toBe(true);
    expect(обстоятельства.every(([имя]) => имя === "entity_type")).toBe(true);
    expect(участники.map(([, значение]) => значение)).toEqual(обстоятельства.map(([, значение]) => значение));
  });

  it("режим «все» не фильтрует", () => {
    expect(параметрыРежима("все", счётчики)).toEqual([]);
  });

  // Сервер отвечает 400 unknown_entity_type на любой отсутствующий тип.
  it("не запрашивает тип, которого нет в корпусе", () => {
    const значения = (параметрыРежима("обстоятельства", счётчики) ?? []).map(([, значение]) => значение);
    expect(значения).toEqual(["auth_session", "ip_address", "process"]);
    expect(значения.length).toBeLessThan(ТИПЫ_ОБСТОЯТЕЛЬСТВ.length);
    expect(известныеТипыОбстоятельств(счётчики)).toEqual(значения);
  });

  // null, а не пустой набор: пустой набор — это «показать всё», и список
  // сеансов был бы принят за список учётных записей.
  it("без словаря и без участников возвращает null, а не пустой фильтр", () => {
    expect(параметрыРежима("участники", undefined)).toBeNull();
    expect(параметрыРежима("участники", [{ entity_type: "ad_user", count: 5 }])).toEqual([]);
    expect(параметрыРежима("обстоятельства", undefined)).toBeNull();
    expect(параметрыРежима("все", undefined)).toEqual([]);
  });
});

describe("разделение полно по построению", () => {
  // Новый source pack не должен молча исчезать из режима по умолчанию.
  it("неизвестный тип остаётся видимым среди участников", () => {
    const сНовым = [...счётчики, { entity_type: "exchange_mailbox", count: 77 }];
    const участники = числоВРежиме("участники", сНовым) ?? 0;
    const обстоятельства = числоВРежиме("обстоятельства", сНовым) ?? 0;
    const все = числоВРежиме("все", сНовым) ?? 0;
    expect(участники + обстоятельства).toBe(все);
    expect(участники).toBe((числоВРежиме("участники", счётчики) ?? 0) + 77);
  });

  it("сумма двух режимов равна общему числу", () => {
    expect((числоВРежиме("участники", счётчики) ?? 0) + (числоВРежиме("обстоятельства", счётчики) ?? 0)).toBe(числоВРежиме("все", счётчики));
  });
});

describe("подпись режима", () => {
  it("называет, сколько скрыто", () => {
    expect(подписьРежима("участники", счётчики)).toContain("скрыто");
    expect(подписьРежима("участники", счётчики)).toContain((2_683_510).toLocaleString("ru-RU"));
  });

  // Число из среза в пятьдесят строк нельзя выдавать за общее.
  it("без счётчиков сервера ничего не выдумывает", () => {
    expect(числоВРежиме("участники", undefined)).toBeNull();
    expect(числоВРежиме("участники", [])).toBeNull();
    expect(подписьРежима("участники", undefined)).not.toMatch(/\d/);
  });
});
