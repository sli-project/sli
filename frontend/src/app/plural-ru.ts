import { formatNumber } from "../shared/format";
/*
  `О2` из talk/ОБЩИЕ_ДЕФЕКТЫ_ИНТЕРФЕЙСА_20260731.md.

  На живом экране очереди проблем стояло «1 шагов», «1 доказательств». Подпись
  собиралась склейкой числа с одной фиксированной формой слова, поэтому была
  верна при `70` и неверна при `1`. Единого помощника склонения в `frontend/src`
  не было: поиск по `склон|plural|падеж` не давал ничего, — значит дефект
  воспроизводился в каждом новом месте, где кто-то писал `${n} доказательств`.

  Владелец назвал это классом визуальных ошибок, а не опечаткой. Поэтому здесь
  закрывается класс: одна функция с тремя формами вместо правки отдельных
  подписей. Правка подписей вариантом «шагов: 1» тоже убирает ошибку, но не
  мешает написать её заново.
*/

/** Три формы существительного: для 1, для 2, для 5. */
export type ТриФормы = readonly [одна: string, две: string, пять: string];

/**
 * Русское склонение по числу.
 *
 * Правило: `11`–`14` всегда берут форму «пять» независимо от последней цифры,
 * поэтому `11 политик`, а не `11 политика`. Отрицательные и дробные значения
 * склоняются по модулю целой части — на экране они не встречаются, но молча
 * ломаться не должны.
 */
export function формаСлова(число: number, формы: ТриФормы): string {
  const целое = Math.abs(Math.trunc(число));
  const десятки = целое % 100;
  if (десятки >= 11 && десятки <= 14) return формы[2];
  const единицы = целое % 10;
  if (единицы === 1) return формы[0];
  if (единицы >= 2 && единицы <= 4) return формы[1];
  return формы[2];
}

/**
 * Число и согласованное с ним слово.
 *
 * Число форматируется по-русски с разделителем разрядов, потому что `1400`
 * читается хуже, чем `1 400`, а разнобой между экранами уже встречался.
 */
export function числоСоСловом(число: number, формы: ТриФормы): string {
  return `${formatNumber(число)} ${формаСлова(число, формы)}`;
}

