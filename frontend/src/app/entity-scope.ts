import { formatNumber } from "../shared/format";
/**
 * Разделение списка сущностей на участников и обстоятельства.
 *
 * Список сущностей почти целиком состоит из сеансов входа: `auth_session`
 * создаётся из `LogonId` у каждого события входа и выхода, а эти два события —
 * подавляющая часть корпуса. Человек, открывающий раздел «Сущности», ищет
 * учётную запись или компьютер, а получает страницы шестнадцатеричных номеров
 * сеансов.
 *
 * Участник — тот, о ком спрашивают: учётная запись, компьютер, группа, служба,
 * задача, актив. Обстоятельство — то, чем и откуда действие выполнено: сеанс,
 * адрес, процесс.
 *
 * **Разделение полное по построению.** Обстоятельства имеют небольшой
 * известный перечень технических типов, а участники являются его отрицанием.
 * Поэтому новый тип из будущего source pack по умолчанию остаётся видимым
 * среди участников, а не исчезает в скрытом режиме. Когда источник объявит
 * новый технический тип, его можно явно классифицировать как обстоятельство.
 *
 * Значения взяты из вызовов `_append_entity()` в `server/app/entity_model.py`.
 * Канал и поставщик — `log_source` и `event_provider` — тоже обстоятельства:
 * они описывают, откуда пришла запись, а не кто в происшествии участвовал.
 */

import { t } from "../i18n";

/** Технические типы, которые описывают обстоятельство, а не участника. */
export const ТИПЫ_ОБСТОЯТЕЛЬСТВ: readonly string[] = [
  "auth_session",
  "ip_address",
  "process",
  "event_provider",
  "log_source",
];

export type РежимСущностей = "участники" | "обстоятельства" | "все";

export function РЕЖИМЫ_СУЩНОСТЕЙ(): ReadonlyArray<{ режим: РежимСущностей; подпись: string; пояснение: string }> {
  return [
    { режим: "участники", подпись: t("entities.scope.mode.participants.label"), пояснение: t("entities.scope.mode.participants.hint") },
    { режим: "обстоятельства", подпись: t("entities.scope.mode.circumstances.label"), пояснение: t("entities.scope.mode.circumstances.hint") },
    { режим: "все", подпись: t("entities.scope.mode.all.label"), пояснение: t("entities.scope.mode.all.hint") },
  ];
}

/**
 * Типы обстоятельств, которые в корпусе действительно встречаются.
 *
 * Сервер отвечает `400 unknown_entity_type`, если запрошен тип, которого нет ни
 * у одной сущности: `get_entities_workspace_data()` сверяет запрошенное со
 * списком существующих и отказывает **целиком**, а не пропускает лишнее. Пяти
 * постоянных значений поэтому отправлять нельзя: достаточно, чтобы в корпусе не
 * оказалось `process`, и оба режима перестанут открываться.
 *
 * Поэтому перечень пересекается со словарём типов, который сервер присылает в
 * `type_counts` при каждом ответе.
 */
export function известныеТипыОбстоятельств(
  счётчики: ReadonlyArray<{ entity_type?: string; count?: number }> | undefined,
): string[] {
  if (!счётчики?.length) return [];
  const есть = new Set(счётчики.map((строка) => String(строка.entity_type ?? "").toLowerCase()));
  return ТИПЫ_ОБСТОЯТЕЛЬСТВ.filter((тип) => есть.has(тип));
}

/**
 * Параметры запроса для режима. Пустой набор означает «сервер не фильтрует».
 *
 * `null` — «фильтровать нужно, но нечем»: словарь типов ещё не получен, либо
 * запрошены обстоятельства, а ни одного технического типа в корпусе нет.
 * Запрос тогда не отправляется, иначе отсутствие фильтра выглядело бы как его
 * применение и список сеансов сошёл бы за список учётных записей.
 *
 * Пустой набор у участников — случай другой и честный: обстоятельств нет,
 * исключать нечего, значит все сущности и есть участники.
 */
export function параметрыРежима(
  режим: РежимСущностей,
  счётчики: ReadonlyArray<{ entity_type?: string; count?: number }> | undefined,
): Array<[string, string]> | null {
  if (режим === "все") return [];
  if (!счётчики?.length) return null;
  const типы = известныеТипыОбстоятельств(счётчики);
  if (!типы.length) return режим === "участники" ? [] : null;
  const имя = режим === "участники" ? "exclude_entity_type" : "entity_type";
  return типы.map((тип) => [имя, тип]);
}

/**
 * Сколько сущностей относится к режиму по данным `type_counts` сервера.
 *
 * Возвращает `null`, когда сервер счётчиков не прислал: показывать вычисленное
 * из среза число как общее было бы неправдой — срез ограничен пятьюдесятью
 * строками.
 */
export function числоВРежиме(
  режим: РежимСущностей,
  счётчики: ReadonlyArray<{ entity_type?: string; count?: number }> | undefined,
): number | null {
  if (!счётчики?.length) return null;
  const обстоятельства = new Set(ТИПЫ_ОБСТОЯТЕЛЬСТВ);
  let итог = 0;
  for (const строка of счётчики) {
    const тип = String(строка.entity_type ?? "").toLowerCase();
    const число = Number(строка.count ?? 0);
    if (!Number.isFinite(число)) continue;
    const этоУчастник = !обстоятельства.has(тип);
    if (режим === "все" || (режим === "участники") === этоУчастник) итог += число;
  }
  return итог;
}

/**
 * Подпись о том, что именно скрыто. Молчаливое сокрытие хуже шума: человек
 * должен видеть, что список показывает не всё, и одним нажатием это отменить.
 */
export function подписьРежима(
  режим: РежимСущностей,
  счётчики: ReadonlyArray<{ entity_type?: string; count?: number }> | undefined,
): string {
  const всего = числоВРежиме("все", счётчики);
  const вРежиме = числоВРежиме(режим, счётчики);
  if (всего === null || вРежиме === null) return t("entities.scope.statusNoCount");
  if (режим === "все") return t("entities.scope.statusAll", { count: formatNumber(всего) });
  const скрыто = всего - вРежиме;
  const что = режим === "участники" ? t("entities.scope.what.circumstances") : t("entities.scope.what.participants");
  return t("entities.scope.statusFiltered", { shown: formatNumber(вРежиме), total: formatNumber(всего), hidden: formatNumber(скрыто), what: что });
}
