<#
VDS: powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\SLI-Lab\lab-02-populate.ps1
Owned demo.example DC only. Manifest is generated by lab_model.py, no Python on VDS.
Existing owned objects/members/links are reused; foreign name collisions fail closed.
User passwords are generated on VDS, saved before AD creation and never reset on rerun.
Computer objects represent inventory; they are not joined or running workstations.
#>
#Requires -Version 5.1
[CmdletBinding()]
param()
. "$PSScriptRoot\lab-common.ps1"

function Set-LabGpoFile($Gpo, [string]$RelativePath, [string]$Content, [string]$Extension, [Text.Encoding]$Encoding) {
    $dn = 'CN={' + $Gpo.Id.ToString() + '},CN=Policies,CN=System,DC=demo,DC=example'
    $object = Get-ADObject -Identity $dn -Properties gPCFileSysPath, gPCMachineExtensionNames, versionNumber
    $file = Join-Path $object.gPCFileSysPath $RelativePath
    if ((Test-Path -LiteralPath $file) -and [IO.File]::ReadAllText($file) -ceq $Content -and
        ([string]$object.gPCMachineExtensionNames).Contains($Extension)) { return }
    # These are public policy files in this lab's SYSVOL, inheriting normal GPO read ACLs.
    $null = [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($file))
    [IO.File]::WriteAllText($file, $Content, $Encoding)
    $pairs = @([regex]::Matches([string]$object.gPCMachineExtensionNames, '\[[^\]]+\]') | ForEach-Object { $_.Value })
    $extensions = (($pairs + @($Extension)) | Sort-Object -Unique) -join ''
    $version = ([long]$object.versionNumber -band 4294901760) -bor (([long]$object.versionNumber + 1) -band 65535)
    [IO.File]::WriteAllText((Join-Path $object.gPCFileSysPath 'GPT.INI'), "[General]`r`nVersion=$version`r`n", [Text.Encoding]::ASCII)
    Set-ADObject -Identity $dn -Replace @{ gPCMachineExtensionNames = $extensions; versionNumber = $version }
}

function Invoke-LabPopulate {
    Assert-LabAdministrator
    Initialize-LabDirectory
    $domain = Assert-LabDomain
    Import-Module GroupPolicy
    $manifest = Get-Content -LiteralPath "$PSScriptRoot\lab-data.json" -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($manifest.domain -cne 'demo.example' -or $manifest.marker -cne $script:LabMarker) { throw 'lab_manifest_invalid' }
    $dn = $domain.DistinguishedName
    $ouPaths = @{}
    foreach ($name in @('Отделы', 'Серверы', 'Рабочие станции', 'Сервисные')) {
        $path = "OU=$name,$dn"
        $null = Ensure-LabObject { Get-ADOrganizationalUnit -Filter "DistinguishedName -eq '$path'" -Properties Description } {
            New-ADOrganizationalUnit -Name $name -Path $dn -Description $script:LabMarker -PassThru
        }
        $ouPaths[$name] = $path
    }
    foreach ($name in $manifest.departments) {
        $parent = $ouPaths['Отделы']
        $path = "OU=$name,$parent"
        $null = Ensure-LabObject { Get-ADOrganizationalUnit -Filter "DistinguishedName -eq '$path'" -Properties Description } {
            New-ADOrganizationalUnit -Name $name -Path $parent -Description $script:LabMarker -PassThru
        }
        $ouPaths[$name] = $path
    }
    Initialize-LabDirectory "$script:LabRoot\credentials"
    foreach ($user in $manifest.users) {
        $sam = $user.sam
        $passwordPath = "$script:LabRoot\credentials\$sam.secret"
        $existing = Get-ADUser -Filter "SamAccountName -eq '$sam'" -Properties Description
        if ($existing) {
            Assert-LabOwned $existing
            if (-not (Test-Path -LiteralPath $passwordPath)) { throw 'lab_existing_password_missing' }
            continue
        }
        if (-not (Test-Path -LiteralPath $passwordPath)) { Write-LabSecret $passwordPath (New-LabPassword) }
        $password = ConvertTo-SecureString ([IO.File]::ReadAllText((Assert-LabPath $passwordPath))) -AsPlainText -Force
        $params = @{
            Name = $user.display_name; DisplayName = $user.display_name; SamAccountName = $sam
            UserPrincipalName = "$sam@demo.example"; Path = $ouPaths[$user.department]
            Description = $script:LabMarker; AccountPassword = $password; Enabled = [bool]$user.enabled
            ChangePasswordAtLogon = $false; PasswordNeverExpires = [bool]$user.service
        }
        if (-not $user.service) { $params.GivenName = $user.given_name; $params.Surname = $user.surname; $params.Department = $user.department }
        if ($user.spns.Count) { $params.ServicePrincipalNames = @($user.spns) }
        New-ADUser @params
    }
    foreach ($computer in $manifest.computers) {
        $name = $computer.name
        $null = Ensure-LabObject { Get-ADComputer -Filter "Name -eq '$name'" -Properties Description } {
            New-ADComputer -Name $name -SamAccountName ($name + '$') -DNSHostName "$name.demo.example" `
                -Path $ouPaths[$computer.ou] -Description $script:LabMarker -Enabled $true -PassThru
        }
    }
    foreach ($name in $manifest.groups) {
        $null = Ensure-LabObject { Get-ADGroup -Filter "Name -eq '$name'" -Properties Description } {
            New-ADGroup -Name $name -SamAccountName $name -GroupScope Global -GroupCategory Security `
                -Path $ouPaths['Сервисные'] -Description $script:LabMarker -PassThru
        }
    }
    for ($i = 0; $i -lt 8; $i++) {
        $group = 'LAB-Department-{0:00}' -f ($i + 1)
        $members = @((Get-ADGroup $group -Properties Member).Member)
        foreach ($user in @($manifest.users | Where-Object { $_.department -eq $manifest.departments[$i] })) {
            $member = Get-ADUser $user.sam
            if ($members -notcontains $member.DistinguishedName) { Add-ADGroupMember $group $member }
        }
        $all = Get-ADGroup 'LAB-All' -Properties Member
        $department = Get-ADGroup $group
        if ($all.Member -notcontains $department.DistinguishedName) { Add-ADGroupMember 'LAB-All' $department }
    }
    foreach ($group in @('LAB-VPN', 'LAB-Operators')) {
        $member = Get-ADUser 'lab.u001'
        if ((Get-ADGroup $group -Properties Member).Member -notcontains $member.DistinguishedName) { Add-ADGroupMember $group $member }
    }
    $operators = Get-ADGroup 'LAB-Operators'
    $privileged = Get-ADGroup 'S-1-5-32-551' -Properties Member
    if ($privileged.Member -notcontains $operators.DistinguishedName) { Add-ADGroupMember $privileged $operators }
    # Domain password policy must be set through AD; arbitrary registry values do not implement it.
    Set-ADDefaultDomainPasswordPolicy -Identity $domain.DNSRoot -ComplexityEnabled $true -MinPasswordLength 14 `
        -PasswordHistoryCount 12 -MaxPasswordAge (New-TimeSpan -Days 90) -MinPasswordAge (New-TimeSpan -Days 1) `
        -LockoutThreshold 20 -LockoutDuration (New-TimeSpan -Minutes 15) -LockoutObservationWindow (New-TimeSpan -Minutes 15)
    $policies = @(
        @('LAB-Password', $dn, 'HKLM\SYSTEM\CurrentControlSet\Control\Lsa', 'NoLMHash', 1),
        @('LAB-Audit', $dn, 'HKLM\SYSTEM\CurrentControlSet\Control\Lsa', 'SCENoApplyLegacyAuditPolicy', 1),
        @('LAB-Lock', $dn, 'HKLM\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System', 'InactivityTimeoutSecs', 900),
        @('LAB-Firewall', $dn, 'HKLM\SOFTWARE\Policies\Microsoft\WindowsFirewall\DomainProfile', 'EnableFirewall', 1),
        @('LAB-Servers', $ouPaths['Серверы'], 'HKLM\SOFTWARE\Policies\Microsoft\Windows NT\Terminal Services', 'fDenyTSConnections', 1),
        @('LAB-Workstations', $ouPaths['Рабочие станции'], 'HKLM\SOFTWARE\Policies\Microsoft\Windows\Personalization', 'NoLockScreenCamera', 1),
        @('LAB-VPN', $ouPaths['Рабочие станции'], 'HKLM\SOFTWARE\Policies\Microsoft\Windows\Network Connections', 'NC_ShowSharedAccessUI', 0),
        @('LAB-Updates', $dn, 'HKLM\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate\AU', 'NoAutoRebootWithLoggedOnUsers', 1)
    )
    foreach ($policy in $policies) {
        $gpo = Get-GPO -Name $policy[0] -ErrorAction SilentlyContinue
        if ($gpo) { Assert-LabOwned $gpo } else { $gpo = New-GPO -Name $policy[0] -Comment $script:LabMarker }
        $value = Get-GPRegistryValue -Guid $gpo.Id -Key $policy[2] -ValueName $policy[3] -ErrorAction SilentlyContinue
        if (-not $value -or $value.Value -ne $policy[4] -or $value.Type -ne 'DWord') {
            Set-GPRegistryValue -Guid $gpo.Id -Key $policy[2] -ValueName $policy[3] -Type DWord -Value $policy[4] | Out-Null
        }
        $links = @(Get-GPInheritance -Target $policy[1] | Select-Object -ExpandProperty GpoLinks)
        if (@($links | Where-Object { $_.GpoId -eq $gpo.Id }).Count -eq 0) { New-GPLink -Guid $gpo.Id -Target $policy[1] | Out-Null }
        # DS Changes (5136) also requires a SACL on the lab GPC, not only auditpol.
        $adPath = 'AD:\CN={' + $gpo.Id.ToString() + '},CN=Policies,CN=System,' + $dn
        $acl = Get-Acl -Path $adPath -Audit
        $everyone = New-Object Security.Principal.SecurityIdentifier('S-1-1-0')
        $rules = @($acl.GetAuditRules($true, $true, [Security.Principal.SecurityIdentifier]) | Where-Object {
            $_.IdentityReference -eq $everyone -and ($_.ActiveDirectoryRights -band [DirectoryServices.ActiveDirectoryRights]::WriteProperty) -and
            ($_.AuditFlags -band [Security.AccessControl.AuditFlags]::Success)
        })
        if ($rules.Count -eq 0) {
            $rule = New-Object DirectoryServices.ActiveDirectoryAuditRule($everyone,
                [DirectoryServices.ActiveDirectoryRights]::WriteProperty, [Security.AccessControl.AuditFlags]::Success)
            $acl.AddAuditRule($rule)
            Set-Acl -Path $adPath -AclObject $acl
        }
    }
    $passwordPolicy = "[Unicode]`r`nUnicode=yes`r`n[Version]`r`nsignature=`"`$CHICAGO`$`"`r`nRevision=1`r`n[System Access]`r`n" +
        "MinimumPasswordAge = 1`r`nMaximumPasswordAge = 90`r`nMinimumPasswordLength = 14`r`nPasswordComplexity = 1`r`n" +
        "PasswordHistorySize = 12`r`nLockoutBadCount = 20`r`nResetLockoutCount = 15`r`nLockoutDuration = 15`r`nClearTextPassword = 0`r`n"
    Set-LabGpoFile (Get-GPO -Name 'LAB-Password') 'Machine\Microsoft\Windows NT\SecEdit\GptTmpl.inf' $passwordPolicy `
        '[{827D319E-6EAC-11D2-A4EA-00C04F79F83A}{803E14A0-B4FB-11D0-A0D0-00A0C90F574B}]' ([Text.Encoding]::Unicode)
    $audit = "Machine Name,Policy Target,Subcategory,Subcategory GUID,Inclusion Setting,Exclusion Setting,Setting Value`r`n"
    foreach ($guid in @('922f', '9215', '923f', '9235', '9237', '923c')) {
        $audit += ",System,Lab,{0cce$guid-69ae-11d9-bed3-505054503030},Success and Failure,,3`r`n"
    }
    Set-LabGpoFile (Get-GPO -Name 'LAB-Audit') 'Machine\Microsoft\Windows NT\Audit\audit.csv' $audit `
        '[{F3CCC681-B74C-4060-9F26-CD84525DCA2A}{0F3F3735-573D-9804-99E4-AB2A69BA5FD4}]' ([Text.Encoding]::UTF8)
    # GUIDs are language independent: policy change, logon, credential validation,
    # user/security-group management, DS changes. Simulation never disables policy-change auditing.
    foreach ($guid in @('922f', '9215', '923f', '9235', '9237', '923c')) {
        Invoke-LabAudit "{0cce$guid-69ae-11d9-bed3-505054503030}"
    }
    $result = Invoke-LabProcess "$env:WINDIR\System32\gpupdate.exe" @('/target:computer', '/force', '/wait:60')
    if ($result.ExitCode -ne 0) { throw 'lab_gpupdate_failed' }
    Write-Output 'lab_population_ready'
}

if ($MyInvocation.InvocationName -ne '.') {
    try { Invoke-LabPopulate } catch { Write-Output 'lab_population_failed'; exit 1 }
}
