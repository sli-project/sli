"""Лестница опознания и канонизация субъекта. Задачи C1/C2 бэклога 7.2.

Правила описаны в docs/STAGE7_C_IDENTITY_SPINE.md §3 и подтверждены замером на
корпусе 1 875 775 событий (runner/12-опознание-субъекта.cmd).

Лестница подключена к созданию наблюдаемых сущностей через `entity_model.py`.
Неизменяемый SID/GUID становится ключом; переименуемые UPN/SAM остаются
временными обозначениями и псевдонимами. Сведение существующих записей и
перенос ссылок остаются отдельной операцией с сохранением свидетельства.

Почему ключ по SID, а не по имени. Имя учётной записи переименуемо и
переиспользуемо, SID - нет. При ключе по имени переименование разрывает
историю человека надвое, а повторное использование имени после удаления
сливает двух разных людей в одну сущность. Второе опаснее: разрыв заметен,
слияние выглядит как непрерывная история. Замер показал, что ни того, ни
другого в корпусе пока нет - правило нужно как защита, а не как исправление
накопленного.
"""
from __future__ import annotations

import ipaddress
import re
from dataclasses import dataclass, field
from typing import Any

# Bump only when ladder ordering, canonicalization or resolution semantics
# change. Semantic queue and normalized-event identities include this value, so
# a rule change creates a new deterministic replay boundary instead of silently
# reusing an older interpretation.
IDENTITY_RESOLUTION_VERSION = "1.0"

# Ступени лестницы. Первая сработавшая даёт ключ.
СТУПЕНЬ_SID = 1
СТУПЕНЬ_GUID = 2
СТУПЕНЬ_UPN = 3
СТУПЕНЬ_SAM = 4
СТУПЕНЬ_ИМЯ = 5  # не ключ: даёт временное обозначение

УВЕРЕННОСТЬ = {
    СТУПЕНЬ_SID: 1.0,
    СТУПЕНЬ_GUID: 1.0,
    СТУПЕНЬ_UPN: 0.8,
    СТУПЕНЬ_SAM: 0.6,
    СТУПЕНЬ_ИМЯ: 0.3,
}

СОСТОЯНИЕ_РАЗРЕШЕНО = "resolved"
СОСТОЯНИЕ_ВРЕМЕННОЕ = "provisional"
СОСТОЯНИЕ_НЕ_РАЗРЕШЕНО = "unresolved"
СОСТОЯНИЕ_ВНЕШНИЙ = "external"

# Ключом может быть только неизменяемый признак. SID и GUID таковы, UPN и SAM
# нет: они переименуемы, и один и тот же субъект наблюдается то с SID, то без
# него. Замер на 200 000 событий показал, что это не край, а обычное дело -
# семь учётных записей из девяти расхождений распались на пару
# `sam:домен:имя` и `sid:...`, будучи одним человеком.
#
# Поэтому третья и четвёртая ступени дают не ключ, а временное обозначение.
# Отличие от пятой ступени существенно: временное обозначение однозначно в
# момент наблюдения и годится для записи, но подлежит сведению, когда для того
# же субъекта появится SID. Возвращать здесь `resolved` значило бы позволить
# пути записи молча завести вторую сущность рядом с существующей - ровно тот
# дефект, который блок C и должен устранить.
ВРЕМЕННЫЕ_СТУПЕНИ = frozenset({3, 4})

# Закрытый список причин. Свободный текст не допускается: причина должна
# поддаваться подсчёту, иначе доля unresolved не измеряется, а описывается.
ПРИЧИНЫ = frozenset({
    "нет_sid", "нет_домена", "противоречие_sid_и_имени",
    "внешний_домен", "не_субъект",
})

# Не субъекты. В действующем коде "-" отсеивается проверкой, а
# "ANONYMOUS LOGON" - только для SubjectUserName, но не для TargetUserName.
# Правило должно быть одно и объявленное, а не условие в трёх местах.
НЕ_СУБЪЕКТЫ = frozenset({
    "-", "n/a", "null",
    "anonymous logon", "анонимный вход",
    "s-1-0-0",  # нулевой SID: "субъект неизвестен", а не субъект
})
# Пустая строка сюда НЕ входит намеренно. Отсутствие признака и явное
# указание "это не субъект" - разные вещи. В первой редакции пустая строка
# была в списке, и всякое событие без SID объявлялось не имеющим субъекта -
# то есть 5 148 событий корпуса потеряли бы участника вместо того, чтобы
# опознаться на четвёртой ступени.

# Встроенные SID одинаковы на каждой машине, поэтому требуют области.
# Замер подтвердил: S-1-5-18 наблюдается с двух серверов, 17 568 событий.
_ВСТРОЕННЫЙ_SID = re.compile(r"^S-1-5-(18|19|20)$|^S-1-5-32-\d+$", re.IGNORECASE)
_ДОМЕННЫЙ_SID = re.compile(r"^S-1-5-21-\d+-\d+-\d+-\d+$", re.IGNORECASE)
_SID_ВООБЩЕ = re.compile(r"^S-1-\d+(-\d+)*$", re.IGNORECASE)
_GUID = re.compile(r"^\{?[0-9a-f]{8}-([0-9a-f]{4}-){3}[0-9a-f]{12}\}?$", re.IGNORECASE)


@dataclass(frozen=True)
class Опознание:
    ключ: str
    ступень: int
    состояние: str
    уверенность: float
    основание: tuple[str, ...] = ()
    причина: str | None = None
    псевдонимы: tuple[str, ...] = ()
    примечание: str | None = None

    @property
    def временный(self) -> bool:
        """Ключ подлежит сведению, когда появится неизменяемый признак."""
        return self.состояние == СОСТОЯНИЕ_ВРЕМЕННОЕ

    @property
    def пригоден_для_записи(self) -> bool:
        """Можно ли записать наблюдение с этим ключом.

        Событие записывается всегда: потеря события хуже неполного опознания.
        Свойство отвечает на другой вопрос - создавать ли под этим ключом
        сущность. Под временным ключом сущность создаётся, но помечается как
        подлежащая сведению; под пустым - нет.
        """
        return bool(self.ключ)

    def как_словарь(self) -> dict[str, Any]:
        return {
            "ключ": self.ключ,
            "правило": self.ступень,
            "состояние": self.состояние,
            "временный": self.временный,
            "уверенность": self.уверенность,
            "основание": list(self.основание),
            "причина": self.причина,
            "псевдонимы": list(self.псевдонимы),
            "примечание": self.примечание,
        }


def _чисто(значение: Any) -> str:
    return str(значение or "").strip()


def явно_не_субъект(значение: str) -> bool:
    """True только для явного указания, что участника нет.

    Пустое значение сюда не попадает: это отсутствие признака, а не
    утверждение об отсутствии субъекта.
    """
    значение = _чисто(значение)
    return bool(значение) and значение.casefold() in НЕ_СУБЪЕКТЫ


def канон_sid(sid: str) -> str:
    """Верхний регистр: `s-1-5` и `S-1-5` - один субъект."""
    return _чисто(sid).upper()


def канон_guid(guid: str) -> str:
    """Нижний регистр, без фигурных скобок: две записи одного значения."""
    return _чисто(guid).strip("{}").lower()


def канон_upn(upn: str) -> str:
    """Нижний регистр целиком.

    Домен нечувствителен к регистру. Локальная часть формально чувствительна,
    но ни одна реализация Active Directory её так не трактует, и различать их
    значило бы создавать двух субъектов там, где каталог видит одного.
    """
    return _чисто(upn).lower()


def канон_почты(почта: str) -> str:
    """Нижний регистр без автоматического приравнивания к UPN."""
    return _чисто(почта).lower()


def канон_узла(узел: str) -> str:
    """Краткое DNS-имя в нижнем регистре; IP-адрес сохраняется целиком."""
    значение = _чисто(узел).rstrip(".").lower()
    if not значение:
        return ""
    try:
        return ipaddress.ip_address(значение).compressed.lower()
    except ValueError:
        return значение.split(".", 1)[0]


def канон_домена(домен: str, *, короткие: dict[str, str] | None = None,
                 отметить: list[str] | None = None) -> str:
    """Привести домен к краткому имени в нижнем регистре.

    Краткое имя и FQDN могут обозначать один домен. Без таблицы соответствий
    эти две формы дают разные ключи.
    """
    значение = _чисто(домен).lower()
    if not значение:
        return ""
    if короткие and значение in короткие:
        return короткие[значение]
    if "." in значение:
        # FQDN без таблицы соответствий: берём первую метку. Допущение верно
        # ровно тогда, когда краткое имя совпадает с первой меткой. Если оно
        # отличается, возникают два ключа для одного домена. Случай помечается
        # и виден в результате опознания.
        if отметить is not None:
            отметить.append(
                f"домен {значение!r} приведён к первой метке без таблицы "
                "соответствий: если краткое имя домена отличается от неё, "
                "ключ разойдётся с ключом того же субъекта из другого события"
            )
        return значение.split(".", 1)[0]
    return значение


def канон_sam(имя: str) -> str:
    """Нижний регистр, `$` сохраняется: он часть имени, а не признак."""
    значение = _чисто(имя)
    if "\\" in значение:
        значение = значение.rsplit("\\", 1)[1]
    return значение.lower()


def разобрать_домен_из_имени(имя: str) -> tuple[str, str]:
    """Вернуть (домен, имя) для форм `DOMAIN\\user` и `user@domain`."""
    значение = _чисто(имя)
    if "\\" in значение:
        домен, _, короткое = значение.rpartition("\\")
        return домен, короткое
    return "", значение


def разрешить_субъект(
    *,
    sid: str | None = None,
    guid: str | None = None,
    upn: str | None = None,
    почта: str | None = None,
    sam: str | None = None,
    домен: str | None = None,
    узел: str | None = None,
    известные_домены: dict[str, str] | None = None,
    свои_домены: frozenset[str] | None = None,
) -> Опознание:
    """Опознать субъекта по первой сработавшей ступени лестницы.

    `узел` обязателен для локальных и встроенных субъектов: их идентификатор
    уникален только в пределах машины. Замер показал, что это не редкий
    случай - `MAG-TOM-LEN141`, `KRSK-009`, `EX1` в поле домена суть имена
    машин с локальными учётными записями.
    """
    sid = канон_sid(sid or "")
    guid = канон_guid(guid or "")
    upn = канон_upn(upn or "")
    почта = канон_почты(почта or "")
    sam_сырое = _чисто(sam)
    домен_сырое = _чисто(домен)
    узел_канон = канон_узла(узел or "")

    if not домен_сырое and sam_сырое:
        домен_сырое, sam_сырое = разобрать_домен_из_имени(sam_сырое)
    отметки: list[str] = []
    домен_канон = канон_домена(домен_сырое, короткие=известные_домены, отметить=отметки)

    основание: list[str] = []
    псевдонимы: list[str] = []
    if sam_сырое:
        # Псевдоним `sam:` обязателен и у опознания по SID. Без него временное
        # обозначение того же субъекта нечем связать с постоянным ключом, и
        # сведение придётся делать вручную. Замер показал, что случай не
        # редкий: семь учётных записей из девяти расхождений наблюдались и с
        # SID, и без него.
        псевдонимы.append(f"sam:{домен_канон or '?'}:{канон_sam(sam_сырое)}")
    if upn:
        псевдонимы.append(f"upn:{upn}")
    if почта and "@" in почта:
        # Почта и UPN намеренно остаются разными типами псевдонима. Их
        # совпадение — политика конкретной организации, не свойство AD.
        псевдонимы.append(f"mail:{почта}")

    # --- явное указание, что участника нет ---
    # Нулевой SID при живом имени субъекта не отменяет: он означает "SID не
    # определён", и опознание должно продолжиться по нижним ступеням. Отбраковка
    # происходит, только когда не осталось ни одного пригодного признака.
    sid_пригоден = bool(sid) and not явно_не_субъект(sid)
    if not sid_пригоден:
        sid = ""
    if явно_не_субъект(sam_сырое) and not sid_пригоден and not upn and not guid:
        return Опознание(
            ключ="", ступень=СТУПЕНЬ_ИМЯ, состояние=СОСТОЯНИЕ_НЕ_РАЗРЕШЕНО,
            уверенность=0.0, причина="не_субъект",
            примечание="прочерк или анонимный вход - участника нет",
        )
    if явно_не_субъект(sam_сырое):
        sam_сырое = ""

    # --- ступень 1: SID ---
    if sid and _SID_ВООБЩЕ.match(sid):
        основание.append("sid")
        if _ВСТРОЕННЫЙ_SID.match(sid):
            if not узел_канон:
                return Опознание(
                    ключ="", ступень=СТУПЕНЬ_SID, состояние=СОСТОЯНИЕ_НЕ_РАЗРЕШЕНО,
                    уверенность=0.0, основание=tuple(основание), причина="нет_домена",
                    псевдонимы=tuple(псевдонимы),
                    примечание=(
                        "встроенный SID без узла: он одинаков на каждой машине, "
                        "и ключ без области слил бы их в один субъект"
                    ),
                )
            return Опознание(
                ключ=f"sid:{узел_канон}:{sid}", ступень=СТУПЕНЬ_SID,
                состояние=СОСТОЯНИЕ_РАЗРЕШЕНО, уверенность=УВЕРЕННОСТЬ[СТУПЕНЬ_SID],
                основание=tuple(основание), псевдонимы=tuple(псевдонимы),
                примечание="встроенный субъект: ключ ограничен узлом",
            )
        состояние = СОСТОЯНИЕ_РАЗРЕШЕНО
        причина = None
        примечание = None
        if _ДОМЕННЫЙ_SID.match(sid) and свои_домены is not None:
            префикс = sid.rsplit("-", 1)[0]
            if префикс.upper() not in {d.upper() for d in свои_домены}:
                состояние = СОСТОЯНИЕ_ВНЕШНИЙ
                причина = "внешний_домен"
                примечание = "SID из незнакомого леса: субъект внешний, но опознан"
        return Опознание(
            ключ=f"sid:{sid}", ступень=СТУПЕНЬ_SID, состояние=состояние,
            уверенность=УВЕРЕННОСТЬ[СТУПЕНЬ_SID], основание=tuple(основание),
            причина=причина, псевдонимы=tuple(псевдонимы), примечание=примечание,
        )

    # --- ступень 2: GUID ---
    if guid and _GUID.match(guid):
        основание.append("guid")
        return Опознание(
            ключ=f"guid:{guid}", ступень=СТУПЕНЬ_GUID, состояние=СОСТОЯНИЕ_РАЗРЕШЕНО,
            уверенность=УВЕРЕННОСТЬ[СТУПЕНЬ_GUID], основание=tuple(основание),
            псевдонимы=tuple(псевдонимы),
        )

    # --- ступень 3: UPN ---
    if upn and "@" in upn:
        основание.append("upn")
        return Опознание(
            ключ=f"upn:{upn}", ступень=СТУПЕНЬ_UPN, состояние=СОСТОЯНИЕ_ВРЕМЕННОЕ,
            уверенность=УВЕРЕННОСТЬ[СТУПЕНЬ_UPN], основание=tuple(основание),
            псевдонимы=tuple(п for п in псевдонимы if not п.startswith("upn:")),
            примечание=(
                "временное обозначение: UPN переименуем, и тот же субъект с SID "
                "получит другой ключ - записи подлежат сведению по псевдониму"
            ),
        )

    # --- ступень 4: домен и SAM ---
    if sam_сырое and домен_канон:
        основание.extend(["domain", "sam"])
        примечание = (
            "временное обозначение: однозначно в момент наблюдения, но тот же "
            "субъект, наблюдённый с SID, получит другой ключ - записи подлежат "
            "сведению по этому же обозначению как псевдониму"
        )
        уверенность = УВЕРЕННОСТЬ[СТУПЕНЬ_SAM]
        if отметки:
            # Домен пришлось угадывать - значит ключ может разойтись с ключом
            # того же субъекта, наблюдённого с кратким именем домена.
            примечание = "; ".join([примечание, *отметки])
            уверенность = round(уверенность / 2, 2)
        обозначение = f"sam:{домен_канон}:{канон_sam(sam_сырое)}"
        return Опознание(
            ключ=обозначение, ступень=СТУПЕНЬ_SAM,
            состояние=СОСТОЯНИЕ_ВРЕМЕННОЕ, уверенность=уверенность,
            основание=tuple(основание),
            # Псевдоним совпадает с ключом намеренно: сведение выполняется
            # поиском по псевдонимам, и запись, опознанная по SID, обязана
            # нести тот же `sam:` среди своих - иначе связать их нечем.
            псевдонимы=tuple(dict.fromkeys([обозначение, *псевдонимы])),
            примечание=примечание,
        )

    # --- ступень 5: имя без домена. Ключом не является ---
    if sam_сырое:
        основание.append("sam")
        return Опознание(
            ключ=f"name:{канон_sam(sam_сырое)}", ступень=СТУПЕНЬ_ИМЯ,
            состояние=СОСТОЯНИЕ_НЕ_РАЗРЕШЕНО, уверенность=УВЕРЕННОСТЬ[СТУПЕНЬ_ИМЯ],
            основание=tuple(основание), причина="нет_домена",
            псевдонимы=tuple(п for п in псевдонимы if not п.startswith("sam:")),
            примечание=(
                "временное обозначение, а не ключ: разные домены могут содержать "
                "одноимённые учётные записи"
            ),
        )

    return Опознание(
        ключ="", ступень=СТУПЕНЬ_ИМЯ, состояние=СОСТОЯНИЕ_НЕ_РАЗРЕШЕНО,
        уверенность=0.0,
        причина="не_субъект" if явно_не_субъект(_чисто(sam)) else "нет_sid",
        примечание="ни одного опознавательного признака",
    )


def свести(опознания: "list[Опознание]") -> dict[str, str]:
    """Сопоставить временные обозначения постоянным ключам через псевдонимы.

    Возвращает отображение «временное обозначение -> постоянный ключ». Пустое
    значение означает, что постоянного ключа для этого обозначения пока не
    встречалось: обозначение остаётся в силе и ждёт.

    Сведение выполняется по псевдониму `sam:`, который несут и постоянный
    ключ, и временное обозначение. Именно ради этого он записывается у обоих.

    Функция не решает, что делать со сведёнными записями: перенос ссылок и
    закрытие лишней сущности - отдельная работа, и она обязана подчиняться
    правилу Р7, сохраняя свидетельство того, что сведение произошло.
    """
    постоянные: dict[str, str] = {}
    for о in опознания:
        if о.состояние in {СОСТОЯНИЕ_РАЗРЕШЕНО, СОСТОЯНИЕ_ВНЕШНИЙ} and о.ключ:
            for псевдоним in о.псевдонимы:
                прежний = постоянные.get(псевдоним)
                if прежний and прежний != о.ключ:
                    # Один псевдоним ведёт к двум постоянным ключам: имя было
                    # переиспользовано. Сводить нельзя - это разные субъекты.
                    постоянные[псевдоним] = ""
                elif прежний is None:
                    постоянные[псевдоним] = о.ключ

    итог: dict[str, str] = {}
    for о in опознания:
        if о.временный and о.ключ:
            итог[о.ключ] = постоянные.get(о.ключ, "")
    return итог


def разрешить_из_события(событие: dict[str, Any], *, роль: str = "target",
                         известные_домены: dict[str, str] | None = None,
                         свои_домены: frozenset[str] | None = None) -> Опознание:
    """Опознать участника события по роли.

    Роль `target` - по умолчанию не случайно. В событии успешного входа
    субъектом является вошедшая учётная запись, и лежит она в `target_*`;
    `subject_*` содержит того, от чьего имени выполнено действие, то есть чаще
    всего систему. Эта ошибка уже допускалась дважды при разборе корпуса,
    поэтому умолчание выбрано так, чтобы неверный вариант приходилось указывать
    явно.
    """
    if роль not in {"target", "subject"}:
        raise ValueError(f"неизвестная роль участника: {роль!r}")
    return разрешить_субъект(
        sid=событие.get(f"{роль}_user_sid"),
        sam=событие.get(f"{роль}_user_name"),
        домен=событие.get(f"{роль}_domain_name"),
        upn=событие.get(f"{роль}_upn"),
        почта=(
            событие.get(f"{роль}_email")
            or событие.get(f"{роль}_mail")
        ),
        узел=событие.get("computer_name") or событие.get("server_name"),
        известные_домены=известные_домены,
        свои_домены=свои_домены,
    )
